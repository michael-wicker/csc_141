# 04_14 PEP 8
# PEP 8 is the Python style guide. It recommends using clear naming,
# spaces around operators, and consistent indentation to make code easier
# to read and maintain. Following PEP 8 helps programmers work together on
# the same codebase, reduces confusion, and makes code more professional.

# Example of code that follows PEP 8 conventions.
favorite_food = "pizza"

print(f"My favorite food is {favorite_food}.")
